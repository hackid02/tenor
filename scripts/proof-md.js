// Builds PROOF.md from deployments/<chainId>.json and proof/<chainId>.json.
//   node scripts/proof-md.js
const fs = require("fs");
const path = require("path");
const ADDR = require("./lib/addresses");

const cid = 31611;
const A = ADDR[cid];
const root = path.join(__dirname, "..");
const dep = JSON.parse(fs.readFileSync(path.join(root, "deployments", `${cid}.json`), "utf8"));
const proofPath = path.join(root, "proof", `${cid}.json`);
const proof = fs.existsSync(proofPath) ? JSON.parse(fs.readFileSync(proofPath, "utf8")) : { steps: [] };
const addr = (a) => `[\`${a}\`](${A.explorer}/address/${a})`;

const lines = [];
lines.push("# Tenor: on-chain proof");
lines.push("");
lines.push(`Everything below is live on **${A.name}** (chain ${cid}) and can be checked on the explorer. Generated by \`node scripts/proof-md.js\`.`);
lines.push("");
lines.push("## Contracts (all verified on the Mezo explorer)");
lines.push("");
lines.push("| Contract | Address |");
lines.push("|---|---|");
lines.push(`| TenorRouter (Mezo CL pools) | ${addr(dep.router)} |`);
if (dep.quoter) lines.push(`| TenorQuoter (exact read-only quotes) | ${addr(dep.quoter)} |`);
for (const [key, m] of Object.entries(dep.markets)) {
  lines.push(`| TenorMarket \`${key}\` (${m.label}, matures ${m.maturityIso.slice(0, 10)}) | ${addr(m.market)} |`);
  lines.push(`| PT-sMUSD-${m.label} | ${addr(m.pt)} |`);
  lines.push(`| YT-sMUSD-${m.label} | ${addr(m.yt)} |`);
  if (m.pool) lines.push(`| PT/MUSD CL pool on Mezo Pools (${m.label}, PT range ${m.clPosition.lowPt}–${m.clPosition.highPt}) | ${addr(m.pool)} |`);
  for (const x of m.extraPositions || []) lines.push(`| Extra one-sided PT liquidity (${x.pt} PT, ${m.label}) | [tx ${x.tx.slice(0, 10)}…](${A.explorer}/tx/${x.tx}) |`);
}
lines.push("");
lines.push("## Mezo contracts Tenor builds on");
lines.push("");
lines.push("| Mezo contract | Address | How Tenor uses it |");
lines.push("|---|---|---|");
lines.push(`| MUSD | ${addr(A.musd)} | Deposit asset, yield asset, quote asset |`);
lines.push(`| sMUSD (MUSD Savings Rate) | ${addr(A.smusd)} | Every PT is backed 1:1 by sMUSD; YT receives its yield |`);
lines.push(`| Mezo Pools CL factory | ${addr(A.clFactory)} | Creates the PT/MUSD pools; the router only accepts pools from it |`);
lines.push(`| Mezo Pools CL position manager | ${addr(A.clPositionManager)} | Concentrated liquidity in the PT price range |`);
lines.push("");
lines.push("## Every user action, run on-chain");
lines.push("");
lines.push("| # | Action | What happened | Transaction |");
lines.push("|---|---|---|---|");
proof.steps.forEach((s, i) => {
  lines.push(`| ${i + 1} | \`${s.action}\` | ${s.what} | [${s.tx.slice(0, 10)}…](${s.link}) |`);
});
lines.push("");
// Usage beyond the team's own proof run, from `node scripts/users.js`.
const usersPath = path.join(root, "docs", "USERS.md");
if (fs.existsSync(usersPath)) {
  const u = fs.readFileSync(usersPath, "utf8");
  const num = (re) => (u.match(re) || [])[1];
  const outW = num(/\*\*Outside wallets\*\*[^|]*\| \*\*(\d+)\*\*/);
  const outT = num(/\*\*Outside wallets\*\*[^|]*\| \*\*\d+\*\* \| \*\*(\d+)\*\*/);
  const teamW = num(/Team and Team QA wallets[^|]*\| (\d+)/);
  lines.push("## Who else has used it");
  lines.push("");
  lines.push(`Read from the chain by \`node scripts/users.js\`: **${outW} outside wallet${outW === "1" ? "" : "s"}** (${outT} transaction${outT === "1" ? "" : "s"}) and ${teamW} team and Team QA wallets. Every wallet is listed in [docs/USERS.md](docs/USERS.md); the QA runs are in [docs/QA.md](docs/QA.md).`);
  lines.push("");
}
lines.push("## Design note: why CL pools");
lines.push("");
lines.push("Tenor first used a Mezo **stable** pool for PT/MUSD. Stable pools concentrate liquidity at a price of exactly 1, but PT trades below 1 (about 0.984 for 12% APY), so a few small trades moved the fixed APY from 11.8% to 2.4%. Those first transactions are kept in [`proof/31611-stable-pool-v1.json`](proof/31611-stable-pool-v1.json).");
lines.push("");
lines.push("Tenor now uses Mezo **concentrated-liquidity** pools with liquidity placed only where PT trades. With the same ~1,000 MUSD of liquidity, a 50 MUSD purchase locks 11.35% when the pool quotes 12.00%.");
lines.push("");
fs.writeFileSync(path.join(root, "PROOF.md"), lines.join("\n"));
console.log(`PROOF.md written with ${proof.steps.length} transactions`);
